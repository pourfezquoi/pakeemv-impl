/****************************************************************************************
SPI0 pad configurating function
=========================================================================================
SPI0_MISO		(GP3)
SPI0_MOSI		(GP4)
SPI0_SS0		(GP1)
SPI0_SCK		(GP0)
-----------------------------------------------------------------------------------------
Quad_Mode:  0	- Ignore SPI0_SPIO2 & SPI0_SPIO3
			1	- Enable SPI0_SPIO2 & SPI0_SPIO3
-----------------------------------------------------------------------------------------
If enabled,
SPI0_SPIO2	(GP5)
SPI0_SPIO3	(GP6)
-----------------------------------------------------------------------------------------
SSx_Enabled: 0	- Enable SPI0_SS0
			 1	- Enable SPI0_SS1
			 2	- Enable SPI0_SS0 & SPI0_SS1
			 SPI0_SS1(master only)
-----------------------------------------------------------------------------------------
If enabled,
SPI0_SS1		(GP2)
****************************************************************************************/
